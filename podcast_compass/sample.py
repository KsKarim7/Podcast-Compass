"""The committed sample episode and the result the app produced from it.

Keeping a generated result in the repository means the interface demonstrates its full
output with no API call: useful when the daily allowance is spent, when no key is
configured, or when a reviewer simply wants to see the shape of the thing first.

The result is produced by tools/generate_sample.py, which runs the same pipeline as the
app. It is regenerated whenever the prompts or the schema change, so it never shows
output the current code could not produce.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from .models import EpisodeResult

SAMPLES_DIR = Path(__file__).resolve().parent.parent / "samples"
TRANSCRIPT_PATH = SAMPLES_DIR / "sample_episode.vtt"
RESULT_PATH = SAMPLES_DIR / "sample_results.json"

TRANSCRIPT_LABEL = "Original script written for this demo, not a real podcast recording."

MISSING_RESULT_MESSAGE = (
    "The pre-generated sample has not been created yet. Run tools/generate_sample.py "
    "with an API key to produce samples/sample_results.json."
)


@dataclass(frozen=True)
class SampleBundle:
    transcript: str
    result: EpisodeResult
    generated_at: str
    model: str

    @property
    def label(self) -> str:
        return (
            f"Pre-generated with this app on {self.generated_at} using {self.model}. "
            "No API call was made just now."
        )


def load_transcript() -> str:
    return TRANSCRIPT_PATH.read_text(encoding="utf-8")


def result_exists() -> bool:
    return RESULT_PATH.is_file()


def load_bundle() -> SampleBundle:
    """Raises FileNotFoundError with a message the interface can show as-is."""
    if not result_exists():
        raise FileNotFoundError(MISSING_RESULT_MESSAGE)

    payload = json.loads(RESULT_PATH.read_text(encoding="utf-8"))
    return SampleBundle(
        transcript=load_transcript(),
        result=EpisodeResult.model_validate(payload["result"]),
        generated_at=payload["generated_at"],
        model=payload["model"],
    )


def save_bundle(result: EpisodeResult, *, generated_at: str, model: str) -> None:
    """Used by tools/generate_sample.py, never by the running app."""
    payload = {
        "generated_at": generated_at,
        "model": model,
        "note": (
            "Generated by tools/generate_sample.py from samples/sample_episode.vtt using "
            "the same pipeline as the app. Regenerate after changing prompts or schema."
        ),
        "result": result.model_dump(),
    }
    RESULT_PATH.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
